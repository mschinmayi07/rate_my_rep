# Load reps
with open("az_reps_final.json") as f:
    reps = json.load(f)

# Build district → rep names lookup
district_to_reps = {}
for rep in reps:
    d = str(rep["district"])
    if d not in district_to_reps:
        district_to_reps[d] = []
    district_to_reps[d].append(rep["name"])

print("Districts with reps in our dataset:")
for d in sorted(district_to_reps.keys(), key=lambda x: int(x) if x.isdigit() else 99):
    print(f"  District {d}: {district_to_reps[d]}")

# Build final zip → rep names map
zip_to_reps = {}
for zipcode, district in AZ_ZIP_TO_DISTRICT.items():
    rep_names = district_to_reps.get(district, [])
    if rep_names:
        zip_to_reps[zipcode] = rep_names

print(f"\nTotal zip codes mapped: {len(zip_to_reps)}")

# Save
with open("zip_to_reps.json", "w") as f:
    json.dump(zip_to_reps, f, indent=2)

